// proceedRequest.test.ts — does a finished answer end by asking the user to reply "proceed"?
// The rail, the LIVE board and the phone show a P until someone replies (Oct 23 2026).
import { describe, it, expect } from 'vitest';
import { asksForProceed, lastAnswerAsksForProceed, PROCEED_TAIL_CHARS } from '../server/proceedRequest.js';

describe('asksForProceed', () => {
  it.each([
    'Reply **proceed** to build with these recommendations, or answer 1–4.',
    'Reply proceed to run the test as above, or tell me which engines or downloads to drop.',
    'Say "proceed" and I will start.',
    'Type `proceed` when you are ready.',
    'Send proceed or tell me what to change.',
    "I'll wait for your proceed before touching the code.",
    'Waiting for your "proceed" confirmation before implementing!',
    'Shall I proceed?',
    'Should I proceed with the migration?',
    'Want me to proceed?',
    'Ready to proceed?',
    '回复 proceed 即可开始。',
    'Reply: proceed',
    '确认后请回复「proceed」。',
    '发送 proceed 开始构建。',
    'Reply "go" or "proceed" when ready.',
    'Shall I proceed with the migration (i.e. drop the old table)?',
  ])('asks: %s', (text) => {
    expect(asksForProceed(`Here is the plan.\n\n${text}`)).toBe(true);
  });

  it.each([
    'Done. The tests pass and the DMG is installed.',
    'I proceeded with the build and it passed.',
    'The queue can proceed once the hold clears.',
    'We can proceed later if you want.',
    'No need to reply proceed: it already ran.',
    "You don't have to type proceed this time.",
    'The rail shows a P when an answer says `reply proceed` near its end.',
    'Can I proceed without a password? Yes: the key works too.',
    '',
  ])('does not ask: %s', (text) => {
    expect(asksForProceed(text)).toBe(false);
  });

  it('only reads the end of the answer: an early mention does not count', () => {
    const early = 'Earlier you said: reply proceed to build.\n\n' + 'Then I built it. '.repeat(80) + '\nAll done.';
    expect(early.length).toBeGreaterThan(PROCEED_TAIL_CHARS);
    expect(asksForProceed(early)).toBe(false);
  });

  it('ignores a quote inside a code block', () => {
    expect(asksForProceed('The template ends with:\n```\nReply proceed to build.\n```\nThat line is gone now.')).toBe(false);
  });

  it('a long answer still counts when the ask is its last line', () => {
    const long = 'Detail line.\n'.repeat(500) + 'Reply **proceed** to build it.';
    expect(asksForProceed(long)).toBe(true);
  });
});

const line = (e: object) => JSON.stringify(e);
const user = (content: unknown, extra: object = {}) => line({ type: 'user', message: { role: 'user', content }, ...extra });
const assistant = (content: unknown[], extra: object = {}) => line({ type: 'assistant', message: { role: 'assistant', content }, ...extra });
const text = (t: string) => ({ type: 'text', text: t });

describe('lastAnswerAsksForProceed (transcript, for a resumed session)', () => {
  const ask = assistant([text('Plan above. Reply **proceed** to build.')]);

  it('true when the last answer asks and nothing was typed since', () => {
    expect(lastAnswerAsksForProceed([user('plan it'), assistant([{ type: 'thinking', thinking: '' }]), ask])).toBe(true);
  });

  it('skips system entries, meta lines, harness tags and side chains after the answer', () => {
    const lines = [
      user('plan it'),
      ask,
      line({ type: 'system', subtype: 'stop_hook_summary' }),
      user('<local-command-stdout>Set model to opus</local-command-stdout>'),
      user('Caveat: messages below were generated by the user', { isMeta: true }),
      user('side question', { isSidechain: true }),
      '{"type":"assist', // the line Claude Code is still writing
    ];
    expect(lastAnswerAsksForProceed(lines)).toBe(true);
  });

  it('false once the user replied', () => {
    expect(lastAnswerAsksForProceed([ask, user('proceed')])).toBe(false);
    expect(lastAnswerAsksForProceed([ask, user([text('use option B')])])).toBe(false);
  });

  it('a pasted image or text that only looks like a tag is still a reply; harness lines are not', () => {
    expect(lastAnswerAsksForProceed([ask, user([{ type: 'image', source: { type: 'base64', media_type: 'image/png', data: 'x' } }])])).toBe(false);
    expect(lastAnswerAsksForProceed([ask, user('<div> is misaligned, fix that first')])).toBe(false);
    expect(lastAnswerAsksForProceed([ask, user('<command-name>/model</command-name>')])).toBe(true);
  });

  it('false when the user interrupted, or the turn ended on a tool call', () => {
    expect(lastAnswerAsksForProceed([ask, user([text('[Request interrupted by user]')])])).toBe(false);
    expect(lastAnswerAsksForProceed([user('go'), assistant([{ type: 'tool_use', id: 't', name: 'Bash', input: {} }])])).toBe(false);
  });

  it('false when the last answer does not ask, or there is no answer', () => {
    expect(lastAnswerAsksForProceed([user('go'), assistant([text('All done.')])])).toBe(false);
    expect(lastAnswerAsksForProceed([])).toBe(false);
  });
});
