// test/chatClaudeTranscript.test.ts — AASC-41: Claude's JSONL as chat entries, read in pages from a byte
// cursor. Synthetic transcripts in a temp dir (test/chatFixtures.ts); no real transcript is read.
import { appendFileSync, rmSync, writeFileSync, renameSync } from 'node:fs';
import { join } from 'node:path';
import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { readClaudeChatPage } from '../server/chat/claudeTranscript.js';
import type { ChatEntry } from '../src/types/chat.js';
import { appendJsonl, claude, jsonl, tempDir, writeJsonl } from './chatFixtures.js';

let dir = '';
let file = '';

beforeEach(() => {
  dir = tempDir('aasc41-claude-');
  file = join(dir, 'transcript.jsonl');
});
afterEach(() => {
  rmSync(dir, { recursive: true, force: true });
});

/** The entries without their key and time, for comparing shapes. */
const bare = (entries: ChatEntry[]) => entries.map(({ key: _k, timestamp: _t, ...rest }) => rest);

async function entriesOf(records: unknown[]): Promise<ChatEntry[]> {
  writeJsonl(file, records);
  return (await readClaudeChatPage(file)).entries;
}

describe('Claude records → chat entries', () => {
  it('maps prompts, replies, tool calls and their results', async () => {
    const entries = await entriesOf([
      claude.user('fix the bug'),
      claude.assistant([claude.text('Looking.'), claude.toolUse('tu1', 'Bash', { command: 'ls', description: 'List' })]),
      claude.result('tu1', 'a.txt\nb.txt'),
      claude.result('tu2', [{ type: 'text', text: 'boom' }, { type: 'image', source: { data: 'AAAA' } }], true),
      claude.assistant('Done.'),
    ]);
    expect(bare(entries)).toEqual([
      { kind: 'user', text: 'fix the bug' },
      { kind: 'assistant', text: 'Looking.' },
      { kind: 'tool_use', id: 'tu1', name: 'Bash', input: { command: 'ls', description: 'List' } },
      { kind: 'tool_result', toolUseId: 'tu1', isError: false, output: 'a.txt\nb.txt', truncated: false },
      { kind: 'tool_result', toolUseId: 'tu2', isError: true, output: 'boom\n[image]', truncated: false },
      { kind: 'assistant', text: 'Done.' },
    ]);
  });

  it('gives keys unique in the file and the records’ own times', async () => {
    const records = [claude.user('one'), claude.assistant([claude.text('a'), claude.text('b')]), { type: 'user', message: { role: 'user', content: 'no time' } }];
    const entries = await entriesOf(records);
    const keys = entries.map((e) => e.key);
    expect(new Set(keys).size).toBe(4);
    expect(keys[0]).toBe('0:0');
    expect(keys[1]).toMatch(/^\d+:0$/);
    expect(keys[2]).toBe(keys[1].replace(/:0$/, ':1'));
    expect(entries[0].timestamp).toBe(Date.parse(records[0].timestamp as string));
    expect(entries[3].timestamp).toBe(Date.parse(records[1].timestamp as string));
  });

  it('marks thinking by length and duration, never sending the thinking', async () => {
    const entries = await entriesOf([
      claude.assistant([claude.thinking('secret plan'), claude.text('ok')], { thinkingDurationMs: 2300 }),
      claude.assistant([claude.thinking('')]),
      claude.assistant([{ type: 'redacted_thinking', data: 'zzz' }]),
    ]);
    expect(bare(entries)).toEqual([
      { kind: 'thinking', length: 11, durationMs: 2300 },
      { kind: 'assistant', text: 'ok' },
      { kind: 'thinking', length: 0 },
      { kind: 'thinking', length: 0 },
    ]);
    expect(JSON.stringify(entries)).not.toContain('secret plan');
  });

  it('turns TodoWrite into a todo list and Agent / Task into subagents', async () => {
    const entries = await entriesOf([
      claude.call('t1', 'TodoWrite', { todos: [{ content: 'Write test', status: 'completed', activeForm: 'Writing' }, { content: 'Fix', status: 'in_progress' }] }),
      claude.call('a1', 'Agent', { description: 'Find callers', prompt: 'Search the repo', subagent_type: 'Explore', run_in_background: true }),
      claude.call('a2', 'Task', { description: 'Review', prompt: 'Review it' }),
      claude.result('a1', 'Found 3 callers'),
    ]);
    expect(bare(entries)).toEqual([
      { kind: 'todo', id: 't1', items: [{ text: 'Write test', status: 'completed' }, { text: 'Fix', status: 'in_progress' }] },
      { kind: 'subagent', id: 'a1', description: 'Find callers', agentType: 'Explore', prompt: 'Search the repo', background: true },
      { kind: 'subagent', id: 'a2', description: 'Review', prompt: 'Review it' },
      { kind: 'tool_result', toolUseId: 'a1', isError: false, output: 'Found 3 callers', truncated: false },
    ]);
  });

  it('shows slash commands with what they printed, and drops the caveat boilerplate', async () => {
    const entries = await entriesOf([
      claude.user('<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond.</local-command-caveat>', { isMeta: true }),
      claude.user('<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args>opus</command-args>'),
      claude.system('local_command', { content: '<local-command-stdout>Set model to opus</local-command-stdout>' }),
      claude.system('local_command', { content: '<command-name>/effort</command-name><command-message>effort</command-message><command-args>high</command-args>' }),
      claude.user('<local-command-stdout>Set effort to high</local-command-stdout>'),
      claude.user('<local-command-stdout>orphan output</local-command-stdout>'),
    ]);
    expect(bare(entries)).toEqual([
      { kind: 'command', name: '/model', args: 'opus', output: 'Set model to opus' },
      { kind: 'command', name: '/effort', args: 'high', output: 'Set effort to high' },
      { kind: 'system', system: 'info', label: 'command output', text: 'orphan output' },
    ]);
  });

  it('marks cancels, compaction, notifications, injected context and CLI notices', async () => {
    const entries = await entriesOf([
      claude.user([claude.text('[Request interrupted by user for tool use]')]),
      claude.system('compact_boundary', { content: 'Conversation compacted', compactMetadata: { trigger: 'auto', preTokens: 1 } }),
      claude.user('This session is being continued from a previous conversation. Summary: …', { isCompactSummary: true }),
      claude.user('<task-notification>\n<task-id>b1</task-id>\n<status>completed</status>\n</task-notification>'),
      claude.user('<system-reminder>be careful</system-reminder>'),
      claude.user([claude.text('Base directory for this skill: /skills/tdd\n\n# TDD')], { isMeta: true }),
      claude.system('informational', { content: 'Usage limit soon', level: 'warning' }),
      claude.assistant('API Error: 529 overloaded', { isApiErrorMessage: true }),
    ]);
    expect(bare(entries)).toEqual([
      { kind: 'system', system: 'cancelled' },
      { kind: 'system', system: 'compacted', label: 'auto' },
      { kind: 'system', system: 'context', label: 'compact summary', text: 'This session is being continued from a previous conversation. Summary: …' },
      { kind: 'system', system: 'notification', label: 'completed', text: '<task-notification>\n<task-id>b1</task-id>\n<status>completed</status>\n</task-notification>' },
      { kind: 'system', system: 'context', label: 'system reminder', text: '<system-reminder>be careful</system-reminder>' },
      { kind: 'system', system: 'context', label: 'tdd', text: 'Base directory for this skill: /skills/tdd\n\n# TDD' },
      { kind: 'system', system: 'info', label: 'warning', text: 'Usage limit soon' },
      { kind: 'system', system: 'info', label: 'API error', text: 'API Error: 529 overloaded' },
    ]);
  });

  it('counts a prompt’s images without sending them', async () => {
    const entries = await entriesOf([
      claude.user([claude.text('what is this?'), { type: 'image', source: { type: 'base64', data: 'QUJD' } }]),
      claude.user([{ type: 'image', source: { type: 'base64', data: 'QUJD' } }]),
    ]);
    expect(bare(entries)).toEqual([
      { kind: 'user', text: 'what is this?', images: 1 },
      { kind: 'user', text: '', images: 1 },
    ]);
    expect(JSON.stringify(entries)).not.toContain('QUJD');
  });

  it('skips sidechain and bookkeeping records', async () => {
    const entries = await entriesOf([
      { type: 'attachment', timestamp: '2026-10-15T10:00:00.000Z', attachment: { type: 'x' } },
      { type: 'file-history-snapshot', snapshot: {} },
      claude.system('turn_duration', { durationMs: 10 }),
      claude.system('stop_hook_summary', { hookCount: 1 }),
      claude.user('subagent prompt', { isSidechain: true }),
      claude.user('real prompt'),
      'not an object',
    ]);
    expect(bare(entries)).toEqual([{ kind: 'user', text: 'real prompt' }]);
  });
});

describe('caps', () => {
  it('cuts text at 16 KB and says so', async () => {
    const [entry] = await entriesOf([claude.assistant('x'.repeat(20_000))]);
    expect(entry).toMatchObject({ kind: 'assistant', truncated: true });
    expect((entry as { text: string }).text.length).toBe(16 * 1024);
  });

  it('cuts a tool input at 2 KB, keeping its shape where it can', async () => {
    const [entry] = await entriesOf([claude.call('b', 'Bash', { command: 'echo '.repeat(1000), description: 'Echo' })]);
    expect(entry).toMatchObject({ kind: 'tool_use', inputTruncated: true });
    const input = (entry as { input: { command: string; description: string } }).input;
    expect(input.description).toBe('Echo');
    expect(JSON.stringify(input).length).toBeLessThanOrEqual(2 * 1024);
  });

  it('keeps an edit tool’s input whole up to 64 KB', async () => {
    const old = 'a'.repeat(15_000);
    const entries = await entriesOf([
      claude.call('e1', 'Edit', { file_path: '/p/a.ts', old_string: old, new_string: `${old}b` }),
      claude.call('w1', 'Write', { file_path: '/p/big.ts', content: 'z'.repeat(70_000) }),
      claude.call('m1', 'MultiEdit', { file_path: '/p/a.ts', edits: [{ old_string: 'a', new_string: 'b' }] }),
    ]);
    expect(entries[0]).toMatchObject({ kind: 'tool_use', input: { old_string: old, new_string: `${old}b` } });
    expect(entries[0]).not.toHaveProperty('inputTruncated');
    expect(entries[1]).toMatchObject({ kind: 'tool_use', name: 'Write', inputTruncated: true });
    expect(JSON.stringify((entries[1] as { input: unknown }).input).length).toBeLessThanOrEqual(64 * 1024);
    expect(entries[2]).toMatchObject({ kind: 'tool_use', name: 'MultiEdit', input: { edits: [{ old_string: 'a', new_string: 'b' }] } });
  });

  it('never sends the data of a result block it can’t show, and caps names', async () => {
    const entries = await entriesOf([
      claude.result('r', [{ type: 'text', text: 'see file' }, { type: 'document', source: { type: 'base64', data: 'SECRETPDF' } }]),
      claude.call('a', 'Agent', { description: 'd', prompt: 'p', subagent_type: 'x'.repeat(1000) }),
      claude.user(`<command-name>/${'n'.repeat(1000)}</command-name>`),
    ]);
    expect(entries[0]).toMatchObject({ kind: 'tool_result', output: 'see file\n[document]' });
    expect(JSON.stringify(entries)).not.toContain('SECRETPDF');
    expect((entries[1] as { agentType: string }).agentType.length).toBeLessThanOrEqual(256);
    expect((entries[2] as { name: string }).name.length).toBeLessThanOrEqual(256);
  });

  it('cuts a tool result at 4 KB and flags it', async () => {
    const [entry] = await entriesOf([claude.result('r', 'y'.repeat(5000))]);
    expect(entry).toMatchObject({ kind: 'tool_result', truncated: true });
    expect((entry as { output: string }).output.length).toBe(4 * 1024);
  });
});

describe('paging', () => {
  /** n prompts, one entry each. */
  const prompts = (n: number, from = 0) => Array.from({ length: n }, (_, i) => claude.user(`p${from + i}`));
  const texts = (entries: ChatEntry[]) => entries.map((e) => (e.kind === 'user' ? e.text : e.kind));

  it('opens on the newest page and walks back with before', async () => {
    writeJsonl(file, prompts(450));
    const last = await readClaudeChatPage(file);
    expect(texts(last.entries)).toEqual(Array.from({ length: 200 }, (_, i) => `p${250 + i}`));
    expect(last.hasMore).toBe(true);

    const middle = await readClaudeChatPage(file, { before: last.before });
    expect(texts(middle.entries)).toEqual(Array.from({ length: 200 }, (_, i) => `p${50 + i}`));
    expect(middle.hasMore).toBe(true);

    const first = await readClaudeChatPage(file, { before: middle.before });
    expect(texts(first.entries)).toEqual(Array.from({ length: 50 }, (_, i) => `p${i}`));
    expect(first.hasMore).toBe(false);
  });

  it('reads what was written since with after, and nothing when nothing was', async () => {
    writeJsonl(file, prompts(3));
    const page = await readClaudeChatPage(file);
    expect((await readClaudeChatPage(file, { after: page.after })).entries).toEqual([]);

    appendJsonl(file, prompts(2, 3));
    const next = await readClaudeChatPage(file, { after: page.after });
    expect(texts(next.entries)).toEqual(['p3', 'p4']);
    expect(next.hasMore).toBe(false);
    // The new entries keep the keys a full read gives them.
    const full = await readClaudeChatPage(file);
    expect(full.entries.slice(-2).map((e) => e.key)).toEqual(next.entries.map((e) => e.key));
  });

  it('leaves a half-written last line for the next read', async () => {
    writeJsonl(file, prompts(1));
    const whole = JSON.stringify(claude.user('late'));
    appendFileSync(file, whole.slice(0, 20));
    const page = await readClaudeChatPage(file);
    expect(texts(page.entries)).toEqual(['p0']);

    appendFileSync(file, `${whole.slice(20)}\n`);
    const next = await readClaudeChatPage(file, { after: page.after });
    expect(texts(next.entries)).toEqual(['late']);
  });

  it('reads a complete last line that has no newline yet, once', async () => {
    writeFileSync(file, jsonl(prompts(1)) + JSON.stringify(claude.user('tail')));
    const page = await readClaudeChatPage(file);
    expect(texts(page.entries)).toEqual(['p0', 'tail']);
    appendFileSync(file, '\n');
    expect((await readClaudeChatPage(file, { after: page.after })).entries).toEqual([]);
  });

  it('stops forward reads at the entry budget and says there is more', async () => {
    writeJsonl(file, prompts(1));
    const page = await readClaudeChatPage(file);
    appendJsonl(file, prompts(5, 1));
    const next = await readClaudeChatPage(file, { after: page.after, limit: 2 });
    expect(texts(next.entries)).toEqual(['p1', 'p2']);
    expect(next.hasMore).toBe(true);
    const rest = await readClaudeChatPage(file, { after: next.after, limit: 10 });
    expect(texts(rest.entries)).toEqual(['p3', 'p4', 'p5']);
    expect(rest.hasMore).toBe(false);
  });

  it('scans at most the byte budget per call', async () => {
    writeJsonl(file, prompts(100));
    const page = await readClaudeChatPage(file, { scanBytes: 1000 });
    expect(page.entries.length).toBeGreaterThan(0);
    expect(page.entries.length).toBeLessThan(20);
    expect(page.hasMore).toBe(true);
    // Walking back with the same budget still reaches the first prompt, with nothing skipped.
    let seen = [...page.entries];
    let before = page.before;
    for (let i = 0; i < 100 && before; i++) {
      const older = await readClaudeChatPage(file, { before, scanBytes: 1000 });
      seen = [...older.entries, ...seen];
      if (!older.hasMore) break;
      before = older.before;
    }
    expect(texts(seen)).toEqual(Array.from({ length: 100 }, (_, i) => `p${i}`));
  });

  it('starts over with reset when the cursor names another file', async () => {
    writeJsonl(file, prompts(3));
    const page = await readClaudeChatPage(file);
    const replacement = join(dir, 'new.jsonl');
    writeJsonl(replacement, prompts(2, 10));
    renameSync(replacement, file);
    const next = await readClaudeChatPage(file, { after: page.after });
    expect(next.reset).toBe(true);
    expect(texts(next.entries)).toEqual(['p10', 'p11']);
  });

  it('starts over with reset when the file got shorter than the cursor', async () => {
    writeJsonl(file, prompts(3));
    const page = await readClaudeChatPage(file);
    writeFileSync(file, jsonl(prompts(1, 20)));
    const next = await readClaudeChatPage(file, { after: page.after });
    expect(next.reset).toBe(true);
    expect(texts(next.entries)).toEqual(['p20']);
  });

  it('refuses a cursor it never made', async () => {
    writeJsonl(file, prompts(1));
    await expect(readClaudeChatPage(file, { before: 'nonsense' })).rejects.toThrow(/cursor/i);
  });

  it('gives an empty page for an empty file', async () => {
    writeFileSync(file, '');
    const page = await readClaudeChatPage(file);
    expect(page.entries).toEqual([]);
    expect(page.hasMore).toBe(false);
    appendJsonl(file, prompts(1));
    expect(texts((await readClaudeChatPage(file, { after: page.after })).entries)).toEqual(['p0']);
  });
});
